const assert=require('node:assert/strict');
const browse=require('../web/browse-state.js');
const value={...browse.defaults(),view:'folders',actor:'演员 / A',studio:'厂商 & B',tags:['标签+1','标签 2','标签+1'],root:'D:/媒体',folder:'A/层级 & 1',recursive:false,search:'ABC+123 %',sort:'date',page:3,filter:'missing'};
assert.deepEqual(browse.parse(browse.href(value)),{...value,tags:['标签+1','标签 2']});
assert.equal(browse.parse('#actors/actor/'+encodeURIComponent('演员/甲')).actor,'演员/甲');
assert.deepEqual(browse.parse('#fields/tag/'+encodeURIComponent('标签 & 1')).tags,['标签 & 1']);
assert.equal(browse.parse('#folders/folder/'+encodeURIComponent(JSON.stringify({root:'/media',path:'目录/二级'}))).folder,'目录/二级');
assert.equal(browse.parse('#library/search/ABC%2F001').search,'ABC/001');
assert.equal(browse.parse('#library?page=-9&sort=unsafe&folder=outside').page,1);
assert.equal(browse.parse('#library?page=bad').page,1);
assert.equal(browse.parse('#library?folder=outside').folder,'');
assert.equal(browse.parse('#library?sort=unsafe').sort,'added');
assert.equal(browse.href({...browse.defaults(),actor:'甲',studio:'乙',tags:['一','二']}),'#library?actor=%E7%94%B2&studio=%E4%B9%99&tag=%E4%B8%80&tag=%E4%BA%8C');
assert.deepEqual(browse.parse('#library?tag=a&tag=b&tag=a').tags,['a','b']);
assert.deepEqual(browse.entity(browse.parse(browse.profile('actor','演员 / 甲'))),{kind:'actor',name:'演员 / 甲'});
assert.deepEqual(browse.entity(browse.parse(browse.profile('studio','厂商 & 乙'))),{kind:'studio',name:'厂商 & 乙'});
assert.equal(browse.entity(browse.parse('#actors')),null);
assert.equal(browse.entity(browse.parse('#library?actor=abc')),null);
assert.equal(browse.parse('#actors/actor/abc').view,'actors');
assert.equal(browse.parse('#fields/studio/abc').view,'fields');
assert.deepEqual(browse.parse(browse.href({...browse.defaults(),view:'actors',actor:'甲',studio:'乙',tags:['一'],page:2})),{...browse.defaults(),view:'actors',actor:'甲',studio:'乙',tags:['一'],page:2});
console.log('PASS browse address round-trip, combined filters, Unicode, pagination and legacy links');
